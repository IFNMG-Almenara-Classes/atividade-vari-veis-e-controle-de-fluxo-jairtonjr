//Escrever um programa para exibir os números de 1 até 50 na tela usando o do..while.
package questao10;

public class Principal {
    public static void main(String[] args) {
        
        int i = 1;
        
        do {
            System.out.println(i);
            i++;
        } while (i <= 50);
    }
}
